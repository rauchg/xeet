//! Deterministic verification of a package.
//!
//! `limitations` is the producer's account of itself; this is the consumer's.
//! Every check here runs without a network, a clock, a renderer or a model.
//! Checks are named and stable, so a caller can gate on specific ones.
//!
//! What verification can establish: the package is internally consistent, its
//! bytes are the bytes it names, its views have the dimensions it claims, its
//! references resolve, its capabilities do not claim authority, and — with a
//! [`Reproducer`] — its views are reproducible from its own inputs.
//!
//! What it cannot establish, and says so: that the source data is authentic,
//! or that anything it describes is still true.

use crate::model::*;
use crate::{asset_path, canon, Package, Reproducer};
use serde::Serialize;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
pub enum Status {
    Pass,
    Warn,
    Fail,
    Skip,
}

#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Check {
    pub name: String,
    pub status: Status,
    pub detail: Vec<String>,
}

#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Verification {
    /// True when no check failed.
    pub ok: bool,
    pub artifact: Option<String>,
    pub checks: Vec<Check>,
    /// Capabilities that need authority from outside this artifact.
    pub requires_external_authority: Vec<String>,
    /// Statements verification cannot make, always present.
    pub cannot_establish: Vec<String>,
}

struct Out {
    checks: Vec<Check>,
}

impl Out {
    fn add(&mut self, name: &str, fails: Vec<String>, warns: Vec<String>) {
        let (status, detail) = if !fails.is_empty() {
            (Status::Fail, fails.into_iter().chain(warns).collect())
        } else if !warns.is_empty() {
            (Status::Warn, warns)
        } else {
            (Status::Pass, Vec::new())
        };
        self.checks.push(Check {
            name: name.to_string(),
            status,
            detail,
        });
    }
    fn skip(&mut self, name: &str, why: &str) {
        self.checks.push(Check {
            name: name.to_string(),
            status: Status::Skip,
            detail: vec![why.to_string()],
        });
    }
}

/// Verifies a package. Pass a reproducer to also check that views can be
/// regenerated byte-for-byte from the preserved inputs.
pub fn verify(package: &Package, reproducer: Option<&dyn Reproducer>) -> Verification {
    let mut out = Out { checks: Vec::new() };
    let cannot_establish = vec![
        "that the source data is authentic (provenance.authenticity says what the producer claims)"
            .to_string(),
        "that any state fact is still true after state.asOf".to_string(),
        "that any capability is still executable, or that the caller holds its authority"
            .to_string(),
    ];

    // --- format and schema -------------------------------------------------
    let format_ok = package.document.get("format").and_then(|v| v.as_str()) == Some(FORMAT);
    let version = package
        .document
        .get("formatVersion")
        .and_then(|v| v.as_str())
        .unwrap_or("");
    let major_ok = version.split('.').next() == FORMAT_VERSION.split('.').next();
    out.add(
        "format",
        [
            (!format_ok).then(|| format!("format is not {FORMAT:?}")),
            (!major_ok)
                .then(|| format!("formatVersion {version:?} is not readable as {FORMAT_VERSION}")),
        ]
        .into_iter()
        .flatten()
        .collect(),
        Vec::new(),
    );
    let artifact = match package.artifact() {
        Ok(a) => {
            out.add("schema", Vec::new(), Vec::new());
            a
        }
        Err(e) => {
            out.add("schema", vec![e], Vec::new());
            return finish(out, None, Vec::new(), cannot_establish);
        }
    };

    // --- identity ----------------------------------------------------------
    let computed = match &package.text {
        Some(text) => canon::document_id_from_text(text),
        None => Ok(canon::document_id(&package.document)),
    };
    out.add(
        "identity",
        match computed {
            Ok(id) if id == artifact.id => Vec::new(),
            Ok(id) => vec![format!(
                "id is {} but the document hashes to {id}",
                artifact.id
            )],
            Err(e) => vec![format!("document text cannot be canonicalized: {e}")],
        },
        Vec::new(),
    );

    // --- assets ------------------------------------------------------------
    let mut fails = Vec::new();
    let mut warns = Vec::new();
    let mut listed = BTreeSet::new();
    for asset in &artifact.assets {
        if !listed.insert(asset.sha256.clone()) {
            fails.push(format!("{} listed twice", asset.sha256));
        }
        if asset.path != asset_path(&asset.sha256, &asset.media_type) {
            fails.push(format!(
                "{}: path {} is not content-derived",
                asset.sha256, asset.path
            ));
        }
        match package.files.get(&asset.path) {
            None => fails.push(format!("{}: missing", asset.path)),
            Some(bytes) => {
                if bytes.len() as u64 != asset.bytes {
                    fails.push(format!(
                        "{}: {} bytes, listed as {}",
                        asset.path,
                        bytes.len(),
                        asset.bytes
                    ));
                }
                let sha = canon::sha256_id(bytes);
                if sha != asset.sha256 {
                    fails.push(format!("{}: hashes to {sha}", asset.path));
                }
            }
        }
    }
    let listed_paths: BTreeSet<&str> = artifact.assets.iter().map(|a| a.path.as_str()).collect();
    for path in package.files.keys() {
        if !listed_paths.contains(path.as_str()) {
            warns.push(format!("{path}: present but not listed"));
        }
    }
    let mut used: BTreeSet<&str> = BTreeSet::new();
    for v in &artifact.views {
        used.insert(&v.asset);
    }
    for i in &artifact.provenance.inputs {
        used.insert(&i.asset);
    }
    for asset in &artifact.assets {
        if !used.contains(asset.sha256.as_str()) {
            warns.push(format!(
                "{}: listed but referenced by no view or input",
                asset.sha256
            ));
        }
    }
    out.add("assets", fails, warns);

    // --- views -------------------------------------------------------------
    let mut fails = Vec::new();
    let mut view_ids = BTreeMap::new();
    for view in &artifact.views {
        if view_ids.insert(view.id.clone(), view).is_some() {
            fails.push(format!("view {} defined twice", view.id));
        }
        if !listed.contains(&view.asset) {
            fails.push(format!("view {}: asset {} not listed", view.id, view.asset));
            continue;
        }
        let expect_w = (view.layout_width * view.scale).ceil() as u32;
        let expect_h = (view.layout_height * view.scale).ceil() as u32;
        if (expect_w, expect_h) != (view.pixel_width, view.pixel_height) {
            fails.push(format!(
                "view {}: layout {}x{} at scale {} is {expect_w}x{expect_h} px, listed as {}x{}",
                view.id,
                view.layout_width,
                view.layout_height,
                view.scale,
                view.pixel_width,
                view.pixel_height
            ));
        }
        if view.media_type == "image/png" {
            match package.asset_bytes(&view.asset).and_then(png_size) {
                Some((w, h)) if (w, h) == (view.pixel_width, view.pixel_height) => {}
                Some((w, h)) => fails.push(format!(
                    "view {}: PNG is {w}x{h}, listed as {}x{}",
                    view.id, view.pixel_width, view.pixel_height
                )),
                None => fails.push(format!("view {}: asset is not a readable PNG", view.id)),
            }
        }
    }
    out.add("views", fails, Vec::new());

    // --- semantic graph ----------------------------------------------------
    let mut fails = Vec::new();
    let mut warns = Vec::new();
    let mut elements = BTreeMap::new();
    for e in &artifact.semantic.elements {
        if elements.insert(e.id.as_str(), e).is_some() {
            fails.push(format!("element {} defined twice", e.id));
        }
    }
    if !elements.contains_key(artifact.semantic.root.as_str()) {
        fails.push(format!("root {} is not an element", artifact.semantic.root));
    }
    if !elements.contains_key(artifact.subject.element.as_str()) {
        fails.push(format!(
            "subject.element {} is not an element",
            artifact.subject.element
        ));
    }
    let mut parents: BTreeMap<&str, &str> = BTreeMap::new();
    for e in &artifact.semantic.elements {
        if !ELEMENT_KINDS.contains(&e.kind.as_str()) {
            if e.kind.contains('.') {
                warns.push(format!("{}: extension kind {}", e.id, e.kind));
            } else {
                fails.push(format!(
                    "{}: kind {:?} is neither universal nor namespaced",
                    e.id, e.kind
                ));
            }
        }
        for c in &e.children {
            if !elements.contains_key(c.as_str()) {
                fails.push(format!("{}: child {c} does not exist", e.id));
            } else if let Some(prev) = parents.insert(c, &e.id) {
                fails.push(format!("{c}: has two parents ({prev}, {})", e.id));
            }
        }
        for b in &e.bounds {
            match view_ids.get(&b.view) {
                None => fails.push(format!("{}: bounds in unknown view {}", e.id, b.view)),
                Some(v) => {
                    let slack = 0.5;
                    let inside = b.x >= -slack
                        && b.y >= -slack
                        && b.w >= 0.0
                        && b.h >= 0.0
                        && b.x + b.w <= v.layout_width + slack
                        && b.y + b.h <= v.layout_height + slack;
                    if !inside {
                        fails.push(format!(
                            "{}: bounds ({}, {}, {}x{}) fall outside view {} ({}x{})",
                            e.id, b.x, b.y, b.w, b.h, v.id, v.layout_width, v.layout_height
                        ));
                    }
                }
            }
        }
        if !e.visible && !e.bounds.is_empty() {
            fails.push(format!("{}: not visible but has bounds", e.id));
        }
    }
    // Every element reachable from the root, and no cycles.
    let mut seen = BTreeSet::new();
    let mut stack = vec![artifact.semantic.root.as_str()];
    while let Some(id) = stack.pop() {
        if !seen.insert(id) {
            fails.push(format!("{id}: reached twice (cycle)"));
            continue;
        }
        if let Some(e) = elements.get(id) {
            stack.extend(e.children.iter().map(String::as_str));
        }
    }
    for id in elements.keys() {
        if !seen.contains(id) {
            warns.push(format!("{id}: not reachable from the root"));
        }
    }
    for r in &artifact.semantic.relations {
        for end in [&r.from, &r.to] {
            if !elements.contains_key(end.as_str()) {
                fails.push(format!(
                    "relation {} {} {}: {end} does not exist",
                    r.from, r.kind, r.to
                ));
            }
        }
    }
    out.add("semantic", fails, warns);

    // --- basis honesty -----------------------------------------------------
    // Anything inferred must be declared as inferred, by subject.
    let declared: BTreeSet<&str> = artifact
        .limitations
        .inferred
        .iter()
        .filter_map(|n| n.subject.as_deref())
        .collect();
    let mut fails = Vec::new();
    let mut inferred = 0;
    for e in &artifact.semantic.elements {
        if e.basis == Basis::Inferred {
            inferred += 1;
            if !declared.contains(e.id.as_str()) {
                fails.push(format!(
                    "{}: inferred but not declared in limitations.inferred",
                    e.id
                ));
            }
        }
    }
    for f in &artifact.state.facts {
        if f.basis == Basis::Inferred {
            inferred += 1;
            if !declared.contains(f.subject.as_str()) {
                fails.push(format!(
                    "{}.{}: inferred but not declared",
                    f.subject, f.key
                ));
            }
        }
    }
    out.add(
        "basis",
        fails,
        if inferred > 0 {
            vec![format!("{inferred} inferred items (declared)")]
        } else {
            Vec::new()
        },
    );

    // --- state -------------------------------------------------------------
    let mut fails = Vec::new();
    if artifact.state.as_of != artifact.provenance.capture.captured_at {
        fails.push("state.asOf differs from provenance.capture.capturedAt".to_string());
    }
    if artifact.state.temporal != "historical-observation" {
        fails.push(format!(
            "state.temporal is {:?}; only a historical observation is representable",
            artifact.state.temporal
        ));
    }
    if artifact.provenance.capture.captured_at.is_empty() {
        fails.push("capture time is empty".to_string());
    }
    for f in &artifact.state.facts {
        if !elements.contains_key(f.subject.as_str()) {
            fails.push(format!(
                "fact {}.{}: subject does not exist",
                f.subject, f.key
            ));
        }
        let unknown = f.basis == Basis::Unknown;
        if unknown != f.value.is_null() {
            fails.push(format!(
                "fact {}.{}: null value must go with basis unknown, and only then",
                f.subject, f.key
            ));
        }
    }
    out.add("state", fails, Vec::new());

    // --- capabilities ------------------------------------------------------
    let mut fails = Vec::new();
    let mut external = Vec::new();
    if artifact.capability_policy != CAPABILITY_POLICY {
        fails.push(format!(
            "capabilityPolicy is {:?}, not {CAPABILITY_POLICY:?}",
            artifact.capability_policy
        ));
    }
    let mut cap_ids = BTreeSet::new();
    for c in &artifact.capabilities {
        if !cap_ids.insert(&c.id) {
            fails.push(format!("capability {} defined twice", c.id));
        }
        if !elements.contains_key(c.target.as_str()) {
            fails.push(format!("{}: target {} does not exist", c.id, c.target));
        }
        let changes_source = matches!(
            c.kind,
            CapabilityKind::Mutation | CapabilityKind::Communication
        );
        if changes_source {
            if c.availability == Availability::LocalExecutable
                || c.executor.kind == ExecutorKind::Local
            {
                fails.push(format!(
                    "{}: a {:?} cannot be executed locally from an artifact",
                    c.id, c.kind
                ));
            }
            if c.authority.required.is_empty() || c.authority.checked_by == "none" {
                fails.push(format!(
                    "{}: a {:?} must name the authority it needs and who checks it",
                    c.id, c.kind
                ));
            }
        }
        if c.availability == Availability::LocalExecutable
            && (c.executor.kind != ExecutorKind::Local || c.kind != CapabilityKind::Projection)
        {
            fails.push(format!(
                "{}: only local projections are local-executable",
                c.id
            ));
        }
        if !c.authority.required.is_empty() || c.executor.kind == ExecutorKind::Origin {
            external.push(c.id.clone());
        }
    }
    out.add("capabilities", fails, Vec::new());

    // --- provenance --------------------------------------------------------
    let mut fails = Vec::new();
    let mut warns = Vec::new();
    for i in &artifact.provenance.inputs {
        if !listed.contains(&i.asset) {
            fails.push(format!("input {} ({}) not listed", i.asset, i.role));
        }
    }
    if artifact.provenance.inputs.is_empty() {
        warns.push("no inputs preserved: the artifact cannot be re-derived".to_string());
    }
    if artifact.provenance.authenticity == Authenticity::Verified {
        warns.push(
            "authenticity is claimed as verified; this verifier cannot check that claim"
                .to_string(),
        );
    }
    if artifact
        .provenance
        .transformations
        .iter()
        .any(|t| !t.deterministic)
    {
        warns.push("some transformations are not deterministic".to_string());
    }
    out.add("provenance", fails, warns);

    // --- coverage ----------------------------------------------------------
    let missing: Vec<String> = COVERAGE_ASPECTS
        .iter()
        .filter(|a| !artifact.coverage.contains_key(**a))
        .map(|a| format!("coverage.{a} is not declared"))
        .collect();
    out.add("coverage", missing, Vec::new());

    // --- reproduction ------------------------------------------------------
    match reproducer {
        Some(r) if r.handles(&artifact.provenance.adapter.name) => {
            match r.reproduce(&artifact, package) {
                Ok(views) => {
                    let mut fails = Vec::new();
                    for v in &artifact.views {
                        match views.get(&v.id) {
                            None => fails.push(format!("view {}: not reproduced", v.id)),
                            Some(bytes) => {
                                let sha = canon::sha256_id(bytes);
                                if sha != v.asset {
                                    fails.push(format!(
                                        "view {}: reproduced {sha}, artifact has {}",
                                        v.id, v.asset
                                    ));
                                }
                            }
                        }
                    }
                    out.add("reproduction", fails, Vec::new());
                }
                Err(e) => out.add("reproduction", vec![e], Vec::new()),
            }
        }
        Some(_) => out.skip("reproduction", "no reproducer for this adapter"),
        None => out.skip("reproduction", "no reproducer supplied"),
    }

    finish(out, Some(artifact.id), external, cannot_establish)
}

fn finish(
    out: Out,
    artifact: Option<String>,
    requires_external_authority: Vec<String>,
    cannot_establish: Vec<String>,
) -> Verification {
    Verification {
        ok: out.checks.iter().all(|c| c.status != Status::Fail),
        artifact,
        checks: out.checks,
        requires_external_authority,
        cannot_establish,
    }
}

/// Width and height from a PNG's IHDR, without decoding it.
pub fn png_size(bytes: &[u8]) -> Option<(u32, u32)> {
    const SIG: &[u8] = b"\x89PNG\r\n\x1a\n";
    if bytes.len() < 24 || &bytes[..8] != SIG || &bytes[12..16] != b"IHDR" {
        return None;
    }
    let w = u32::from_be_bytes(bytes[16..20].try_into().ok()?);
    let h = u32::from_be_bytes(bytes[20..24].try_into().ok()?);
    Some((w, h))
}
